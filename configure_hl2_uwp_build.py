#!/usr/bin/env python3
"""
Prepare the DINO-Unity-21 project for a HoloLens 2 UWP build.

This script automates the project adjustments described in the project notes:

* Switch Unity to Universal Windows Platform (WSAPlayer).
* Configure the UWP target for HoloLens, ARM64, and D3D Project output.
* Enable the Unity-exposed UWP capabilities needed by the project.
* Build a Visual Studio solution when requested.
* Patch Package.appxmanifest with the Research Mode restricted capability.
* Verify that the generated .sln contains Release|ARM64.

The default subcommand is "audit", which performs read-only checks. Use the
explicit subcommands below when you actually want the script to change files:

    python configure_hl2_uwp_build.py configure --unity "C:\\...\\Unity.exe"
    python configure_hl2_uwp_build.py build --unity "C:\\...\\Unity.exe"
    python configure_hl2_uwp_build.py patch-manifest --build-dir ".\\Builds\\DINO-Unity21-UWP"
    python configure_hl2_uwp_build.py all --unity "C:\\...\\Unity.exe"
"""

from __future__ import annotations

